#!/usr/bin/env python3
"""Iteration-2 ablation: does item-level latent appeal (phi) let the same
16 lightweight cold-start heuristics overtake popularity in small catalogs?

Pipeline
--------
1) --generate : produce the catalogs with generator_phi.py
     * data/null_replication/*.json            : iteration-1 pool families
       regenerated by the byte-identical legacy generator path + copies of
       the 4 real pool catalogs (olist x2, uci lights x2);
     * data/main_grid/*.json                   : the phi-aware factorial
       (|V| x entropy x zipf x phi x seed), every phi>0 cell passed through
       the marginals-match gate (phi vs phi=0 on the screen half);
     * out/marginals_match_gate.csv, out/null_replication_bytecheck.csv,
       out/grid_manifest.json.
2) --evaluate: load every catalog through the PORTED catalog_pool adapter
   (unchanged normalization, incl. the deterministic 1000-user subsample)
   and run the PORTED eval_metrics.evaluate_catalog (16 heuristics, k in
   {0,1,2,3,5,8}, temporal 80/20 screen/confirm, L1O-pop) exactly as
   iteration-1.  Emits:
     * out/method_out/method_out_NNNN.json     (exp_gen_sol_out parts),
     * out/aggregates_by_catalog_heuristic_k.csv,
     * out/catalog_diagnostics.csv, out/provenance.jsonl,
     * out/payloads/<catalog_id>.pkl           (rank arrays + diagnostics
       for analyze_ablation.py; a cache, re-derivable from the parts).
3) analyze_ablation.py : headroom per phi, bootstrap CIs, null-vs-extended
   table, null-replication comparison, diagnostic-robustness check.

Usage
-----
  uv run method.py --checks                 # ported C1-C8 + new C9-C12
  uv run method.py --generate               # catalogs + gate + bytecheck
  uv run method.py --evaluate --mode smoke  # 3 tiny catalogs end-to-end
  uv run method.py --evaluate --mode full   # all catalogs
  uv run method.py --all
"""

