def _worker_run(task: dict) -> dict:
    """Runs in a spawn worker.  task: {'kind': 'pool', 'catalog': Catalog}."""
    t0 = time.time()
    cat = task["catalog"]
    from eval_metrics import evaluate_catalog
    payload = evaluate_catalog(cat)
    payload["catalog"] = cat.catalog_id
    # extra per-user split info + family params (needed by analyze_ablation)
    payload["_extra"] = {
        "user_split_pos": np.array(
            [max(0, int(len(u["item_seq"]) * 0.8)) for u in cat.users],
            dtype=np.int32),
        "user_lengths": np.array(
            [len(u["item_seq"]) for u in cat.users], dtype=np.int32),
        "family_params_json": json.dumps(cat.family_params),
        "item_ids_json": json.dumps([str(x) for x in cat.item_ids]),
        "user_ids_json": json.dumps([u["user_id"] for u in cat.users]),
        "n_cat": cat.n_cat,
        "n_price": cat.n_price,
        "n_tags": cat.n_tags,
    }
    summary = {
        "catalog_id": cat.catalog_id,
        "origin": cat.origin,
        "source_name": cat.source_name,
        "source_path": cat.source_path,
        "fold": cat.fold,
        "n_items": cat.n_items,
        "n_users": cat.n_users,
        "wall_s": round(time.time() - t0, 3),
        "cells": {k: int(payload["arrays"][f"{k}/n"]) for k in
                  [str(x) for x in (0, 1, 2, 3, 5, 8)]
                  if f"{k}/n" in payload["arrays"]},
        "item_ids": [str(x) for x in cat.item_ids],
        "user_ids": [u["user_id"] for u in cat.users],
        "screen_pos": [max(0, int(len(u["item_seq"]) * 0.8)) for u in cat.users],
    }
    return {"summary": summary, "payload": payload}


def _select_catalogs(catalogs: list, mode: str, catalog_regex: str | None,
                     max_catalogs: int) -> list:
    import re
    if mode == "smoke":
        pattern = r"^(phi_V20_ELOW_z[0-9.]+_p(0|1)_s0|synth_v20_s0)$"
    else:
        pattern = catalog_regex or r".*"
    rx = re.compile(pattern)
    sel = [c for c in catalogs if rx.match(c.catalog_id)]
    if max_catalogs and max_catalogs > 0:
        sel = sel[:max_catalogs]
    return sel


def write_only_phase(outdir: Path) -> None:
    """Re-serialize parts/aggregates/diagnostics from the payload cache
    (out/payloads/*.pkl) -- used after changing serialization settings."""
    import pickle as _p
    pl_dir = outdir / "payloads"
    payloads_by_id: dict[str, dict] = {}
    summaries_by_id: dict[str, dict] = {}
    for p in sorted(pl_dir.glob("*.pkl")):
        with open(p, "rb") as f:
            payload = _p.load(f)
        payloads_by_id[p.stem] = payload
        extra = payload.get("_extra") or {}
        summaries_by_id[p.stem] = {
            "catalog_id": p.stem,
            "origin": payload.get("origin"),
            "source_name": payload.get("source_name"),
            "source_path": payload.get("source_path"),
            "fold": payload.get("fold"),
            "n_items": payload.get("n_items"),
            "n_users": payload.get("n_users"),
            "cells": {k: int(payload["arrays"][f"{k}/n"]) for k in
                      [str(x) for x in (0, 1, 2, 3, 5, 8)]
                      if f"{k}/n" in payload["arrays"]},
            "item_ids": json.loads(extra.get("item_ids_json", "[]")),
            "user_ids": json.loads(extra.get("user_ids_json", "[]")),
            "screen_pos": [int(x) for x in extra.get("user_split_pos", [])],
        }
    id_mappings: dict[str, dict[str, str]] = {}
    for cid in payloads_by_id:
        ids = summaries_by_id[cid]["item_ids"]
        if ids and max(len(x) for x in ids) > 12:
            id_mappings[cid] = {x: f"p{j}" for j, x in enumerate(ids)}
    run_meta = {
        "item_ids": {cid: summaries_by_id[cid]["item_ids"] for cid in payloads_by_id},
        "user_ids": {cid: summaries_by_id[cid]["user_ids"] for cid in payloads_by_id},
        "screen_pos": {cid: summaries_by_id[cid]["screen_pos"] for cid in payloads_by_id},
        "id_mappings": id_mappings,
    }
    meta = build_meta(0, [], [], 0.0, "uv run method.py --write-only", id_mappings)
    order = sorted(payloads_by_id)
    t_start = time.time()
    parts = output_mod.write_parts(order, payloads_by_id, meta, run_meta,
                                   outdir, wall_started_at=t_start)
    output_mod.write_aggregates(payloads_by_id, outdir)
    output_mod.write_catalog_diagnostics(payloads_by_id, outdir)
    logger.info(f"write-only done: {len(parts)} parts, "
                f"wall {time.time() - t_start:.0f}s")


def evaluate_phase(outdir: Path, mode: str, workers: int | None,
                   catalog_regex: str | None, max_catalogs: int) -> None:
    t_start = time.time()
    outdir.mkdir(parents=True, exist_ok=True)
    (outdir / "payloads").mkdir(parents=True, exist_ok=True)

    pool_cats, pool_skipped = catalog_pool.load_pool_catalogs()
    logger.info(f"pool adapter: {len(pool_cats)} usable catalogs, "
                f"{len(pool_skipped)} skipped")
    for s in pool_skipped:
        logger.warning(f"skipped {s['file']}: {s['reason']}")

    tasks = [{"kind": "pool", "catalog": c} for c in pool_cats]
    if mode != "full":
        sel = _select_catalogs(pool_cats, mode, catalog_regex, max_catalogs)
        wanted = {c.catalog_id for c in sel}
        tasks = [t for t in tasks if t["catalog"].catalog_id in wanted]
    elif max_catalogs and max_catalogs > 0:
        tasks = tasks[:max_catalogs]
    logger.info(f"tasks: {len(tasks)} catalogs (mode={mode})")

    from eval_metrics import evaluate_catalog  # noqa: F401  (warm import)

    cpus = _detect_cpus()
    n_workers = workers or min(cpus, 4)
    payloads_by_id: dict[str, dict] = {}
    summaries_by_id: dict[str, dict] = {}
    provenance: list[dict] = []

    def _handle(res: dict) -> None:
        s = res["summary"]
        payloads_by_id[s["catalog_id"]] = res["payload"]
        summaries_by_id[s["catalog_id"]] = s
        provenance.append({
            "catalog_id": s["catalog_id"], "status": "ok", "origin": s["origin"],
            "source_name": s["source_name"], "source_path": s["source_path"],
            "fold": s["fold"], "n_items": s["n_items"], "n_users": s["n_users"],
            "wall_s": s["wall_s"], "cells": s["cells"],
        })
        logger.info(f"done {s['catalog_id']} ({s['n_items']} items, "
                    f"{s['n_users']} users, {s['wall_s']}s)")

    if n_workers > 1 and len(tasks) > 1:
        with ProcessPoolExecutor(max_workers=n_workers,
                                 mp_context=mp.get_context("spawn")) as pool:
            futs = {pool.submit(_worker_run, t): t for t in tasks}
            for fut in as_completed(futs):
                t = futs[fut]
                cid = t["catalog"].catalog_id
                try:
                    res = fut.result()
                except Exception as e:
                    logger.error(f"catalog {cid} FAILED: {type(e).__name__}: {e}")
                    provenance.append({"catalog_id": cid, "status": "failed",
                                       "error": f"{type(e).__name__}: {e}"})
                    continue
                _handle(res)
    else:
        for t in tasks:
            cid = t["catalog"].catalog_id
            try:
                res = _worker_run(t)
            except Exception as e:
                logger.error(f"catalog {cid} FAILED: {type(e).__name__}: {e}")
                provenance.append({"catalog_id": cid, "status": "failed",
                                   "error": f"{type(e).__name__}: {e}"})
                continue
            _handle(res)

    if not payloads_by_id:
        logger.error("no catalogs produced any output")
        sys.exit(1)

    # persist payloads (rank arrays + diagnostics cache for analyze_ablation)
    pl_dir = outdir / "payloads"
    for cid, payload in payloads_by_id.items():
        with open(pl_dir / f"{cid}.pkl", "wb") as f:
            pickle.dump(payload, f, protocol=4)

    id_mappings: dict[str, dict[str, str]] = {}
    for cid in payloads_by_id:
        ids = summaries_by_id[cid]["item_ids"]
        if not ids:
            continue
        if max(len(x) for x in ids) > 12:
            id_mappings[cid] = {x: f"p{j}" for j, x in enumerate(ids)}
    run_meta = {
        "item_ids": {cid: summaries_by_id[cid]["item_ids"] for cid in payloads_by_id},
        "user_ids": {cid: summaries_by_id[cid]["user_ids"] for cid in payloads_by_id},
        "screen_pos": {cid: summaries_by_id[cid]["screen_pos"] for cid in payloads_by_id},
        "id_mappings": id_mappings,
    }

    repro = f"uv run method.py --evaluate --mode {mode}"
    meta = build_meta(n_workers, tasks, pool_skipped, 0.0, repro, id_mappings)
    order = sorted(payloads_by_id)
    parts = output_mod.write_parts(order, payloads_by_id, meta, run_meta, outdir,
                                   wall_started_at=t_start)
    agg = output_mod.write_aggregates(payloads_by_id, outdir)
    diag_path = output_mod.write_catalog_diagnostics(payloads_by_id, outdir)
    meta["total_wall_seconds"] = round(time.time() - t_start, 1)

    prov_path = outdir / "provenance.jsonl"
    with open(prov_path, "w") as f:
        for row in provenance:
            f.write(json.dumps(row) + "\n")

    wall = time.time() - t_start
    logger.info(f"TOTAL wall: {wall:.1f}s; catalogs OK: {len(payloads_by_id)}")
    logger.info(f"parts: {[p.name for p in parts]}")
    logger.info(f"aggregates: {agg.name}; diagnostics: {diag_path.name}")
    logger.info(f"provenance: {prov_path.name}; payloads: {pl_dir}")


