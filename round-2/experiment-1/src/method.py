def _trivial_gate() -> dict:
    return {"gate_KS": 0.0, "gate_max_abs_dev": 0.0, "dHHI": 0.0,
            "dNormEntropy": 0.0, "pass": True, "attempt": 0, "tighten": 0}


def generate_phase(outdir: Path) -> None:
    t0 = time.time()
    outdir.mkdir(parents=True, exist_ok=True)
    MAIN_GRID_DIR.mkdir(parents=True, exist_ok=True)
    NULL_DIR.mkdir(parents=True, exist_ok=True)

    # ---- null replication: legacy byte-identical families ----
    bytecheck: list[dict] = []
    for p in generator_phi.family_grid():
        cat = generator_phi.build_family_legacy(p)
        path = NULL_DIR / f"{cat['catalog_id']}.json"
        blob = json.dumps(cat)
        path.write_text(blob)
        sha = hashlib.sha256(blob.encode()).hexdigest()
        orig_path = Path(_IT1_PROCESSED) / f"{cat['catalog_id']}.json"
        orig_sha = hashlib.sha256(orig_path.read_bytes()).hexdigest() if orig_path.exists() else ""
        bytecheck.append({
            "catalog_id": cat["catalog_id"],
            "n_items": p["n_items"],
            "n_users": p["n_users"],
            "regenerated_sha256": sha,
            "it1_pool_sha256": orig_sha,
            "byte_identical": bool(orig_sha == sha) if orig_sha else "no_it1_file",
        })
        logger.info(f"null-rep {cat['catalog_id']} written "
                    f"(byte-identical={bytecheck[-1]['byte_identical']})")

    # ---- real pool catalogs ----
    copied = []
    for name in _REAL_POOL_FILES:
        src = Path(_IT1_PROCESSED) / name
        if src.exists():
            shutil.copy2(src, NULL_DIR / name)
            copied.append(name)
        else:
            logger.warning(f"real pool file {name} NOT FOUND at {_IT1_PROCESSED}")
    logger.info(f"real pool catalogs copied: {copied}")

    # ---- main grid ----
    specs = full_main_grid_specs()
    max_main = _MAX_MAIN_GRID.get("n", 0)
    if max_main and max_main > 0:
        specs = specs[:max_main]
    gate_rows: list[dict] = []
    phi0_cache: dict[tuple, dict] = {}
    n_written = 0
    n_failed_gate = 0
    for spec in specs:
        key = (spec["n_items"], spec["entropy_level"], spec["zipf_s"], spec["seed"])
        phi = float(spec["phi"])
        if phi == 0.0:
            if key not in phi0_cache:
                phi0_cache[key] = generator_phi.build_family(spec)
            cat = phi0_cache[key]
            gate = _trivial_gate()
        else:
            if key not in phi0_cache:
                phi0_cache[key] = generator_phi.build_family(
                    make_params(spec["n_items"], spec["entropy_level"],
                                spec["zipf_s"], 0.0, spec["seed"]))
            phi0 = phi0_cache[key]
            cat, gate = generator_phi.generate_cell_with_gate(spec, phi0)
            if not gate["pass"]:
                n_failed_gate += 1
        blob = json.dumps(cat)
        (MAIN_GRID_DIR / f"{cat['catalog_id']}.json").write_text(blob)
        n_written += 1
        gate_rows.append({
            "catalog_id": cat["catalog_id"],
            "n_items": spec["n_items"],
            "entropy": spec["entropy_level"],
            "zipf_s": spec["zipf_s"],
            "phi_nominal": phi,
            "phi_effective": float(gate.get("phi_effective", phi)),
            "phi_capped": bool(gate.get("capped", False)),
            "seed": spec["seed"],
            "tighten_used": gate.get("tighten", 0),
            "gate_KS": gate["gate_KS"],
            "gate_max_abs_dev": gate["gate_max_abs_dev"],
            "dHHI": gate["dHHI"],
            "dNormEntropy": gate["dNormEntropy"],
            "gate_pass": bool(gate["pass"]),
        })
        if n_written % 12 == 0 or n_written == len(specs):
            logger.info(f"main grid {n_written}/{len(specs)} written; "
                        f"gate fails so far: {n_failed_gate}")

    # ---- CSV outputs ----
    gate_path = outdir / "marginals_match_gate.csv"
    with open(gate_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(gate_rows[0].keys()))
        w.writeheader()
        w.writerows(gate_rows)

    bc_path = outdir / "null_replication_bytecheck.csv"
    with open(bc_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(bytecheck[0].keys()))
        w.writeheader()
        w.writerows(bytecheck)

    manifest = outdir / "grid_manifest.json"
    manifest.write_text(json.dumps({
        "main_grid_catalogs": n_written,
        "null_replication_catalogs": len(bytecheck),
        "real_pool_catalogs_copied": copied,
        "gate_failures": n_failed_gate,
        "main_grid_dir": str(MAIN_GRID_DIR),
        "null_dir": str(NULL_DIR),
        "wall_s": round(time.time() - t0, 1),
    }, indent=1))
    logger.info(f"generate phase done: {n_written} main-grid catalogs "
                f"({n_failed_gate} gate failures), {len(bytecheck)} null-rep, "
                f"wall {time.time() - t0:.0f}s; gate: {gate_path.name}")


