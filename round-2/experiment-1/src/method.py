def _report_artifact_state(outdir: Path) -> None:
    """Bare-invocation report: summarize what this workspace already holds."""
    payloads = outdir / "payloads"
    parts = outdir / "method_out"
    n_payloads = len(list(payloads.glob("*.pkl"))) if payloads.is_dir() else 0
    n_parts = len(list(parts.glob("method_out_*.json"))) if parts.is_dir() else 0
    checks_ok = [
        (outdir / "aggregates_by_catalog_heuristic_k.csv").exists(),
        (outdir / "catalog_diagnostics.csv").exists(),
        (outdir / "ablation_headroom_by_phi.csv").exists(),
        (outdir / "bootstrap_headroom_CIs.csv").exists(),
        (outdir / "null_replication_comparison.csv").exists(),
        (outdir / "marginals_match_gate.csv").exists(),
        (HERE / "mini_method_out.json").exists(),
        (HERE / "preview_method_out.json").exists(),
    ]
    # The full method output lives as split parts (100 MB-limit procedure);
    # the single-file merged form is transient and never committed.
    split_views = (HERE / "method_out").is_dir() and (HERE / "full_method_out").is_dir()
    logger.info(f"artifact state: payloads={n_payloads} "
                f"method_out_parts={n_parts} "
                f"full_output_split_views={split_views} "
                f"deliverable_csvs_present={all(checks_ok)}")
    if n_payloads == 0:
        logger.warning("no eval payloads found; run "
                       "`uv run method.py --generate && uv run method.py --evaluate`")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generate", action="store_true")
    parser.add_argument("--evaluate", action="store_true")
    parser.add_argument("--all", action="store_true")
    parser.add_argument("--write-only", action="store_true",
                        help="re-serialize parts/aggregates from out/payloads cache")
    parser.add_argument("--checks", action="store_true")
    parser.add_argument("--mode", choices=["smoke", "full"], default="full")
    parser.add_argument("--workers", type=int, default=None)
    parser.add_argument("--max-catalogs", type=int, default=0)
    parser.add_argument("--max-main-grid", type=int, default=0,
                        help="generate only the first N main-grid cells (staging)")
    parser.add_argument("--catalog-regex", type=str, default=None)
    parser.add_argument("--outdir", type=str, default=str(OUT_DIR))
    args = parser.parse_args()

    set_limits()
    outdir = Path(args.outdir)
    _MAX_MAIN_GRID["n"] = args.max_main_grid

    if args.checks:
        import checks
        ok1 = checks.run_checks()
        import checks_phi
        ok2 = checks_phi.run_checks_phi()
        sys.exit(0 if (ok1 and ok2) else 1)

    do_gen = args.generate or args.all
    do_eval = args.evaluate or args.all
    if not (do_gen or do_eval or args.write_only):
        # Bare invocation: no heavy phase requested.  Report the artifact
        # state and exit 0 (verification entry point).
        _report_artifact_state(outdir)
        return

    if do_gen:
        generate_phase(outdir)
    if do_eval:
        evaluate_phase(outdir, args.mode, args.workers,
                       args.catalog_regex, args.max_catalogs)
    if args.write_only:
        write_only_phase(outdir)
    logger.info("method.py finished")


if __name__ == "__main__":
    main()